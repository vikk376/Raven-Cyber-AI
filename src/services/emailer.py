def render_html(subject: str, body_markdown: str, badge: tuple[str, str] | None = None) -> str:
    """badge = (text, hex colour) renders a coloured risk badge above the body."""
    body = markdown.markdown(body_markdown, extensions=["tables", "fenced_code", "sane_lists"])
    badge_html = ""
    if badge:
        color = badge[1] if badge[1].startswith("#") and len(badge[1]) in (4, 7) else "#555555"
        badge_html = f'<div class="badge" style="background:{color}">{html.escape(badge[0])}</div>'
    ts = datetime.now().strftime("%Y-%m-%d %H:%M")
    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><style>{_CSS}</style></head>
<body><div class="card">
<div class="hdr"><h1>{html.escape(subject)}</h1><p>Microsoft Sentinel Security Report &middot; {ts}</p></div>
<div class="body">{badge_html}{body}</div>
<div class="ftr">Generated by {html.escape("Raven Cyber AI")} from Microsoft Sentinel data. Review findings before acting.</div>
</div></body></html>"""


def send_report(subject: str, body_markdown: str, to: str | None = None,
                badge: tuple[str, str] | None = None) -> str:
    """Send the report. Returns the recipient on success, raises on failure."""
    recipient = (to or config.EMAIL_TO).strip()
    if not recipient:
        raise ValueError("No recipient configured (EMAIL_TO).")
    if not (config.SMTP_USER and config.SMTP_PASSWORD):
        raise ValueError("SMTP is not configured (SMTP_USER / SMTP_PASSWORD).")

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = config.EMAIL_FROM or config.SMTP_USER
    msg["To"] = recipient
    msg.attach(MIMEText(body_markdown, "plain", "utf-8"))
    msg.attach(MIMEText(render_html(subject, body_markdown, badge), "html", "utf-8"))

    # certifi's CA bundle: python.org builds on macOS have no system certs
    ctx = ssl.create_default_context(cafile=certifi.where())
    if config.SMTP_SECURITY == "ssl":
        with smtplib.SMTP_SSL(config.SMTP_HOST, config.SMTP_PORT, context=ctx, timeout=30) as s:
            s.login(config.SMTP_USER, config.SMTP_PASSWORD)
            s.sendmail(msg["From"], [recipient], msg.as_string())
    else:
        with smtplib.SMTP(config.SMTP_HOST, config.SMTP_PORT, timeout=30) as s:
            s.ehlo()
            if config.SMTP_SECURITY == "starttls":
                s.starttls(context=ctx)
                s.ehlo()
            s.login(config.SMTP_USER, config.SMTP_PASSWORD)
            s.sendmail(msg["From"], [recipient], msg.as_string())
    return recipient
